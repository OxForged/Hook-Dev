export function renderDeployScript(ctx: ProjectContext): string {
  const { contractName, permissions, template, templateApplies } = ctx;
  const extraArgs = templateApplies ? (template.constructorArgs ?? []) : [];
  const ctorArgs = ["ICLPoolManager(clPoolManager)", ...extraArgs.map((arg) => arg.deployExpr)].join(", ");

  const feeLine =
    ctx.lpFee === undefined
      ? '        console.log("pool fee            : dynamic (LPFeeLibrary.DYNAMIC_FEE_FLAG, 0x800000)");'
      : `        console.log("pool fee            : ${ctx.lpFee} (${(ctx.lpFee / 10_000).toFixed(4)}%)");`;

  return `// SPDX-License-Identifier: MIT
pragma solidity ${SOLC};

import {Script} from "forge-std/Script.sol";
import {console} from "forge-std/console.sol";

import {ICLPoolManager} from "infinity-core/src/pool-cl/interfaces/ICLPoolManager.sol";
import {CLPoolParametersHelper} from "infinity-core/src/pool-cl/libraries/CLPoolParametersHelper.sol";

import {${contractName}} from "../src/${contractName}.sol";

/// @title Deploy${contractName}
/// @notice Deploys the hook and prints the exact \`parameters\` word its pools need.
///
/// @dev Usage against a local devnet started with \`latch devnet\`:
///
///   forge script script/Deploy${contractName}.s.sol:Deploy${contractName} \\
///       --rpc-url http://127.0.0.1:8545 --broadcast
///
/// Environment:
///   PRIVATE_KEY       deployer key (the devnet prints one)
///   CL_POOL_MANAGER   address of CLPoolManager (the devnet prints it)
///   TICK_SPACING      optional, defaults to ${ctx.tickSpacing}
contract Deploy${contractName} is Script {
    /// @dev Generated alongside the hook's getHooksRegistrationBitmap(). The
    /// assertion below is what keeps the two honest at deploy time.
    uint16 internal constant EXPECTED_BITMAP = ${permissions.bitmapHex};

    function run() external {
        uint256 deployerPrivateKey = vm.envUint("PRIVATE_KEY");
        address clPoolManager = vm.envAddress("CL_POOL_MANAGER");
        int256 rawTickSpacing = vm.envOr("TICK_SPACING", int256(${ctx.tickSpacing}));
        require(
            rawTickSpacing >= 1 && rawTickSpacing <= int256(type(int16).max),
            "TICK_SPACING outside CLPoolManager's MIN/MAX_TICK_SPACING"
        );
        // forge-lint: disable-next-line(unsafe-typecast)
        int24 tickSpacing = int24(rawTickSpacing);

        vm.startBroadcast(deployerPrivateKey);
        ${contractName} hook = new ${contractName}(${ctorArgs});
        vm.stopBroadcast();

        uint16 onChainBitmap = hook.getHooksRegistrationBitmap();
        require(onChainBitmap == EXPECTED_BITMAP, "bitmap drifted from the generated constant");

        bytes32 parameters =
            CLPoolParametersHelper.setTickSpacing(bytes32(uint256(onChainBitmap)), tickSpacing);

        console.log("");
        console.log("=== ${contractName} deployed ===");
        console.log("hook                :", address(hook));
        console.log("registration bitmap :", vm.toString(onChainBitmap));
        console.log("pool key parameters :", vm.toString(parameters));
${feeLine}
        console.log("");
        console.log("Use that parameters word verbatim in your PoolKey. Any other value");
        console.log("makes CLPoolManager.initialize revert with HookConfigValidationError.");
    }
}
`;
}

